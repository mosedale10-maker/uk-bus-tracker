/**
 * Refresh src/livery-seed.generated.js from the live bustimes livery CSS used by
 * the operators the map shows by default. Bundling these means the first paint
 * needs no /api/bt-liveries round trip, so buses show their real livery on the
 * very first frame instead of a second later.
 *
 * Run: node scripts/sync-livery-seed.mjs
 */
import { writeFileSync } from "node:fs";

const OPS = ["FPOT", "DAGC", "CRDR", "SLBS", "NATX", "FLIX"];
const ids = new Set();

for (const op of OPS) {
  try {
    const res = await fetch(`https://ukbustracker.co.uk/api/bt-paint?operator=${op}`);
    const data = await res.json();
    for (const row of Array.isArray(data) ? data : []) {
      if (typeof row?.vehicle?.livery === "number") ids.add(row.vehicle.livery);
    }
  } catch {
    /* operator feed may be down — keep whatever we already collected */
  }
}

const seed = {};
for (const id of [...ids].sort((a, b) => a - b)) {
  try {
    const res = await fetch(`https://ukbustracker.co.uk/api/bt-liveries/${id}/`);
    const row = await res.json();
    if (!row?.left_css) continue;
    seed[id] = {
      name: row.name,
      left_css: row.left_css,
      stroke_colour: row.stroke_colour || "",
      white_text: Boolean(row.white_text),
      text_colour: row.text_colour || "",
    };
  } catch {
    /* skip liveries bustimes will not serve right now */
  }
}

const body =
  "/** Auto-generated by scripts/sync-livery-seed.mjs — do not edit by hand. */\n" +
  `export const LIVERY_SEED = ${JSON.stringify(seed, null, 2)};\n`;

writeFileSync(new URL("../src/livery-seed.generated.js", import.meta.url), body);
console.log(`seeded ${Object.keys(seed).length} liveries`);
